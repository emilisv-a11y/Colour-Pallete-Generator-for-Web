import { fontStack, googleFontsUrl } from './fonts'
import { allTokenNames, buildScales, buildTokens, ROLE_KEYS, STEPS, typeOf, type DesignSystem, type Tokens } from './system'
import { exportType, typeScale } from './typography'

export type TokenFormat = 'css' | 'scss' | 'tailwind4' | 'tailwind3' | 'dtcg' | 'tokens-studio' | 'bootstrap' | 'json'

export const TOKEN_FORMATS: { id: TokenFormat; label: string; ext: string; note: string }[] = [
  { id: 'css', label: 'CSS variables (light + dark)', ext: 'css', note: 'Scales and semantic tokens. Dark mode follows the OS, or force it with data-theme="dark" on <html>.' },
  { id: 'scss', label: 'SCSS', ext: 'scss', note: 'Variables and maps for scales and both modes.' },
  { id: 'tailwind4', label: 'Tailwind v4', ext: 'css', note: 'Scales in @theme; semantic tokens switch with dark mode via CSS variables (bg-bg, text-text, bg-primary…).' },
  { id: 'tailwind3', label: 'Tailwind v3 config', ext: 'js', note: 'Pair with the CSS variables export for semantic tokens.' },
  { id: 'dtcg', label: 'Design Tokens (W3C DTCG)', ext: 'json', note: 'Standard format read by Style Dictionary, Figma plugins and more. Semantic tokens reference the scales.' },
  { id: 'tokens-studio', label: 'Tokens Studio for Figma', ext: 'json', note: 'Import in Tokens Studio. Sets: core, light, dark.' },
  { id: 'bootstrap', label: 'Bootstrap 5.3 (Sass)', ext: 'scss', note: 'Put before @import "bootstrap". Includes dark-mode variables.' },
  { id: 'json', label: 'Plain JSON', ext: 'json', note: 'Resolved hex values for scripts and other tools.' },
]

const header = (sys: DesignSystem) => `${sys.name} · generated by D5 WebTool`

function cssBlock(tokens: Tokens, indent = '  ', prefix = '') {
  return allTokenNames()
    .map((n) => `${indent}--${prefix}${n}: ${tokens[n].ref ? `var(--${tokens[n].ref!.replace('.', '-')})` : tokens[n].hex};`)
    .join('\n')
}

function scaleVars(sys: DesignSystem, indent = '  ') {
  const scales = buildScales(sys)
  return ROLE_KEYS.map((r) => scales[r].map((h, i) => `${indent}--${r}-${STEPS[i]}: ${h};`).join('\n')).join('\n')
}

function fontVars(sys: DesignSystem, indent = '  ') {
  return `${indent}--font-heading: ${fontStack(sys.fonts.heading, sys.fonts.meta)};\n${indent}--font-body: ${fontStack(sys.fonts.body, sys.fonts.meta)};\n${indent}--radius: ${sys.radius}px;`
}

export function exportTokens(sys: DesignSystem, format: TokenFormat): string {
  const scales = buildScales(sys)
  const light = buildTokens(sys, 'light', scales)
  const dark = buildTokens(sys, 'dark', scales)
  const names = allTokenNames()

  switch (format) {
    case 'css':
      return `/* ${header(sys)} */
/* Fonts: <link rel="stylesheet" href="${googleFontsUrl([sys.fonts.heading, sys.fonts.body], sys.fonts.meta)}"> */
:root {
  /* scales */
${scaleVars(sys)}

${fontVars(sys)}

  /* semantic: light */
${cssBlock(light)}
  color-scheme: light;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${cssBlock(dark, '    ')}
    color-scheme: dark;
  }
}

:root[data-theme='dark'] {
${cssBlock(dark)}
  color-scheme: dark;
}

${exportType(typeOf(sys), 'css', sys.fonts, { heading: fontStack(sys.fonts.heading, sys.fonts.meta), body: fontStack(sys.fonts.body, sys.fonts.meta) })}`
    case 'scss': {
      const map = (t: Tokens) => names.map((n) => `  '${n}': ${t[n].hex},`).join('\n')
      return `// ${header(sys)}
${ROLE_KEYS.map((r) => scales[r].map((h, i) => `$${r}-${STEPS[i]}: ${h};`).join('\n')).join('\n\n')}

$scales: (
${ROLE_KEYS.map((r) => `  '${r}': (${scales[r].map((h, i) => `${STEPS[i]}: ${h}`).join(', ')}),`).join('\n')}
);

$theme-light: (
${map(light)}
);

$theme-dark: (
${map(dark)}
);

$font-heading: ${fontStack(sys.fonts.heading, sys.fonts.meta)};
$font-body: ${fontStack(sys.fonts.body, sys.fonts.meta)};
$radius: ${sys.radius}px;

// Usage: @each $name, $value in $theme-light { --#{$name}: #{$value}; }
`
    }
    case 'tailwind4':
      return `/* ${header(sys)} */
@import "tailwindcss";

@custom-variant dark (&:where([data-theme=dark], [data-theme=dark] *));

@theme {
${ROLE_KEYS.map((r) => scales[r].map((h, i) => `  --color-${r}-${STEPS[i]}: ${h};`).join('\n')).join('\n')}

  --font-heading: ${fontStack(sys.fonts.heading, sys.fonts.meta)};
  --font-body: ${fontStack(sys.fonts.body, sys.fonts.meta)};
  --radius-brand: ${sys.radius}px;
}

/* Semantic colours: use bg-bg, bg-surface, text-text, bg-primary, text-on-primary, border-border… */
@theme inline {
${names.map((n) => `  --color-${n}: var(--${n});`).join('\n')}
}

:root {
${names.map((n) => `  --${n}: ${light[n].hex};`).join('\n')}
}

[data-theme=dark] {
${names.map((n) => `  --${n}: ${dark[n].hex};`).join('\n')}
}

${exportType(typeOf(sys), 'tailwind4')}`
    case 'tailwind3':
      return `// ${header(sys)}
// Semantic colours read CSS variables: add the "CSS variables" export to your stylesheet.
/** @type {import('tailwindcss').Config} */
module.exports = {
  darkMode: ['class', '[data-theme="dark"]'],
  theme: {
    extend: {
      colors: {
${ROLE_KEYS.map((r) => `        ${r}: {\n${scales[r].map((h, i) => `          ${STEPS[i]}: '${h}',`).join('\n')}${r === 'neutral' ? '' : `\n          DEFAULT: 'var(--${r})',`}\n        },`).join('\n')}
${names
  .filter((n) => !ROLE_KEYS.includes(n as never))
  .map((n) => `        '${n}': 'var(--${n})',`)
  .join('\n')}
      },
      fontFamily: {
        heading: [${JSON.stringify(sys.fonts.heading)}, 'sans-serif'],
        body: [${JSON.stringify(sys.fonts.body)}, 'sans-serif'],
      },
      borderRadius: { brand: '${sys.radius}px' },
    },
  },
}
`
    case 'dtcg': {
      const color = (v: string, desc?: string) => ({ $type: 'color', $value: v, ...(desc ? { $description: desc } : {}) })
      const sem = (t: Tokens) => Object.fromEntries(names.map((n) => [n, color(t[n].ref ? `{color.${t[n].ref}}` : t[n].hex, t[n].overridden ? 'manual override' : undefined)]))
      return (
        JSON.stringify(
          {
            $description: header(sys),
            color: Object.fromEntries(ROLE_KEYS.map((r) => [r, Object.fromEntries(scales[r].map((h, i) => [String(STEPS[i]), color(h)]))])),
            theme: { light: sem(light), dark: sem(dark) },
            font: {
              heading: { $type: 'fontFamily', $value: [sys.fonts.heading, 'sans-serif'] },
              body: { $type: 'fontFamily', $value: [sys.fonts.body, 'sans-serif'] },
            },
            radius: { base: { $type: 'dimension', $value: { value: sys.radius, unit: 'px' } } },
          },
          null,
          2,
        ) + '\n'
      )
    }
    case 'tokens-studio': {
      const tok = (v: string) => ({ value: v, type: 'color' })
      const sem = (t: Tokens) => Object.fromEntries(names.map((n) => [n, tok(t[n].ref ? `{${t[n].ref}}` : t[n].hex)]))
      return (
        JSON.stringify(
          {
            core: {
              ...Object.fromEntries(ROLE_KEYS.map((r) => [r, Object.fromEntries(scales[r].map((h, i) => [String(STEPS[i]), tok(h)]))])),
              radius: { value: String(sys.radius), type: 'borderRadius' },
              'font-heading': { value: sys.fonts.heading, type: 'fontFamilies' },
              'font-body': { value: sys.fonts.body, type: 'fontFamilies' },
            },
            light: sem(light),
            dark: sem(dark),
            $themes: [],
            $metadata: { tokenSetOrder: ['core', 'light', 'dark'] },
          },
          null,
          2,
        ) + '\n'
      )
    }
    case 'bootstrap':
      return `// ${header(sys)}
// Place before @import "bootstrap/scss/bootstrap";
$primary:   ${light.primary.hex};
$secondary: ${light.secondary.hex};
$success:   ${light.success.hex};
$info:      ${light.info.hex};
$warning:   ${light.warning.hex};
$danger:    ${light.error.hex};
$light:     ${light.surface.hex};
$dark:      ${scales.neutral[9]};

$body-bg:          ${light.bg.hex};
$body-color:       ${light.text.hex};
$secondary-color:  ${light['text-muted'].hex};
$border-color:     ${light.border.hex};
$link-color:       ${light['primary-text'].hex};
$focus-ring-color: rgba(${hexRgb(light['focus-ring'].hex)}, .5);
$border-radius:    ${sys.radius}px;

$font-family-sans-serif: ${fontStack(sys.fonts.body, sys.fonts.meta)};
$headings-font-family:   ${fontStack(sys.fonts.heading, sys.fonts.meta)};

// Dark colour mode (Bootstrap 5.3+, <html data-bs-theme="dark">)
$body-bg-dark:          ${dark.bg.hex};
$body-color-dark:       ${dark.text.hex};
$secondary-color-dark:  ${dark['text-muted'].hex};
$border-color-dark:     ${dark.border.hex};
$link-color-dark:       ${dark['primary-text'].hex};

// Full scales, e.g. for utilities
${ROLE_KEYS.map((r) => scales[r].map((h, i) => `$${r}-${STEPS[i]}: ${h};`).join('\n')).join('\n')}
`
    case 'json':
      return (
        JSON.stringify(
          {
            name: sys.name,
            scales: Object.fromEntries(ROLE_KEYS.map((r) => [r, Object.fromEntries(scales[r].map((h, i) => [STEPS[i], h]))])),
            light: Object.fromEntries(names.map((n) => [n, light[n].hex])),
            dark: Object.fromEntries(names.map((n) => [n, dark[n].hex])),
            fonts: sys.fonts,
            radius: sys.radius,
            typography: Object.fromEntries(typeScale(typeOf(sys)).map((t) => [t.name, { clamp: t.css, minPx: t.min, maxPx: t.max, lineHeight: t.lineHeight }])),
          },
          null,
          2,
        ) + '\n'
      )
  }
}

function hexRgb(hex: string) {
  const n = parseInt(hex.slice(1), 16)
  return `${(n >> 16) & 255}, ${(n >> 8) & 255}, ${n & 255}`
}
